//! Early GOP linear framebuffer bitmap console renderer.

use core::ptr::write_volatile;
use core::sync::atomic::{AtomicBool, Ordering};
use knightboot_protocol::{KbipFramebuffer, KbipPixelFormat};

const CHAR_W: u32 = 8;
const CHAR_H: u32 = 8;
const SCALE: u32 = 1;

static FB_READY: AtomicBool = AtomicBool::new(false);
static mut FB_STATE: FbConsoleState = FbConsoleState::empty();

struct FbConsoleState {
    fb: KbipFramebuffer,
    col: u32,
    row: u32,
    max_cols: u32,
    max_rows: u32,
    fg: u32,
    bg: u32,
}

impl FbConsoleState {
    const fn empty() -> Self {
        Self {
            fb: KbipFramebuffer::empty(),
            col: 0,
            row: 0,
            max_cols: 0,
            max_rows: 0,
            fg: 0x00EC_F0F1,
            bg: 0x0011_161D,
        }
    }
}

fn pack_color(fmt: KbipPixelFormat, rgb: u32) -> u32 {
    let r = (rgb >> 16) & 0xFF;
    let g = (rgb >> 8) & 0xFF;
    let b = rgb & 0xFF;
    match fmt {
        KbipPixelFormat::Rgbx8888 => r | (g << 8) | (b << 16),
        KbipPixelFormat::Bgrx8888 | KbipPixelFormat::BitMask | KbipPixelFormat::Unknown => {
            b | (g << 8) | (r << 16)
        }
    }
}

pub fn init(fb: &KbipFramebuffer) {
    if fb.virt_base == 0 || fb.width < 16 || fb.height < 16 || fb.pitch_bytes == 0 {
        return;
    }
    let fmt = fb.format();
    let fg = pack_color(fmt, 0x00E6_EDF3);
    let bg = pack_color(fmt, 0x000D_1117);

    unsafe {
        let state = &mut *(&raw mut FB_STATE);
        *state = FbConsoleState {
            fb: *fb,
            col: 1,
            row: 1,
            max_cols: (fb.width / (CHAR_W * SCALE)).saturating_sub(2),
            max_rows: (fb.height / (CHAR_H * SCALE)).saturating_sub(2),
            fg,
            bg,
        };
        clear_screen(state);
    }
    FB_READY.store(true, Ordering::Release);
}

unsafe fn clear_screen(state: &FbConsoleState) {
    let pitch_px = (state.fb.pitch_bytes / 4) as usize;
    let ptr = state.fb.virt_base as *mut u32;
    for y in 0..state.fb.height as usize {
        for x in 0..state.fb.width as usize {
            unsafe {
                write_volatile(ptr.add(y * pitch_px + x), state.bg);
            }
        }
    }
}

pub fn write_byte(b: u8) {
    if !FB_READY.load(Ordering::Acquire) {
        return;
    }
    unsafe {
        let state = &mut *(&raw mut FB_STATE);
        match b {
            b'\r' => state.col = 1,
            b'\n' => {
                state.col = 1;
                state.row += 1;
                if state.row >= state.max_rows {
                    state.row = 1;
                    clear_screen(state);
                }
            }
            ch => {
                if state.col >= state.max_cols {
                    state.col = 1;
                    state.row += 1;
                    if state.row >= state.max_rows {
                        state.row = 1;
                        clear_screen(state);
                    }
                }
                draw_char(state, state.col * CHAR_W * SCALE, state.row * CHAR_H * SCALE, ch);
                state.col += 1;
            }
        }
    }
}

unsafe fn draw_char(state: &FbConsoleState, px: u32, py: u32, ch: u8) {
    let glyph = glyph_8x8(ch);
    let pitch_px = (state.fb.pitch_bytes / 4) as usize;
    let base = state.fb.virt_base as *mut u32;

    for (gy, &bits) in glyph.iter().enumerate() {
        for gx in 0..8usize {
            let on = (bits & (0x80 >> gx)) != 0;
            let color = if on { state.fg } else { state.bg };
            let x = px as usize + gx;
            let y = py as usize + gy;
            if x < state.fb.width as usize && y < state.fb.height as usize {
                unsafe {
                    write_volatile(base.add(y * pitch_px + x), color);
                }
            }
        }
    }
}

